// Types of the watch check („Czy mój zegarek jest obsługiwany?”, spec 2026-10-24 §4.11), split out
// of the matcher prototype so the UI can use them without loading the list. Pure, no DOM, no i18n.

export type { Tokens } from './words';

/** What a watch app may read beyond steps and heart rate. */
export type Cap = 'stress' | 'bodyBattery' | 'rides';

/** The short answer of a list row, an option of the field and the remembered model. */
export type Short = 'ok' | 'part' | 'no' | 'notYet' | 'other';

/** A product the watch app supports (from the SDK device files and the manifest). */
export interface Supported {
  id: string;
  series: string;
  names: string[];
  aliases?: string[];
  ciq: string;
  parts: string[];
  lacks?: Cap[];
  newest?: Cap[];
  apac?: { lacks: Cap[]; names?: string[] };
  /**
   * Background memory: 32 — under 64 kB (little room for the background run, the „not tested on a
   * real watch” note), 64 — 64 kB or more. The generator writes it for every product.
   */
  bg?: 32 | 64;
}

/** An SDK device the watch app cannot run on, and why. */
export interface SdkUnsupported {
  id: string;
  series: string;
  names: string[];
  aliases?: string[];
  reason: 'oldCiq' | 'noBackground' | 'noApps' | 'notWatch' | 'notListed';
  kind?: 'bike' | 'handheld';
  ciq?: string;
}

/** `garmin.json`, generated by `npm run garmin:watches`. */
export interface GarminData {
  sdk: string;
  appId: string;
  minCiq: string;
  supported: Supported[];
  unsupported: SdkUnsupported[];
}

/** What the check answers for one thing a person might own. */
export type Verdict =
  | { kind: 'full' }
  | { kind: 'update'; newest: Cap[]; lacks: Cap[] }
  | { kind: 'limited'; lacks: Cap[] }
  | { kind: 'apac'; lacks: Cap[] }
  | { kind: 'oldCiq' | 'noBackground' | 'noApps'; ciq: string }
  | { kind: 'noCiq' }
  | { kind: 'notWatch'; what: 'bike' | 'handheld' | 'band' | 'scale' }
  | { kind: 'notYet' }
  | { kind: 'regional'; of: string }
  | { kind: 'otherBrand'; app?: string; only?: 'ios'; bike: boolean };

export interface Target {
  key: string;
  series: string;
  /** Every official name, the main one first — the store lists them under one entry. */
  names: string[];
  verdict: Verdict;
  /** Supported product id (remembered model, „Połącz zegarek”). */
  id?: string;
}

export interface Hit {
  target: Target;
  /** The official name that fits best — „tactix® 7”, not the store's whole line. */
  name: string;
  /** A store spelling that fits clearly better than any official name („Forerunner 158”, „GarminActive”). */
  as?: string;
  score: number;
  /** Every significant word of the name was typed, none by a typo: an exact model, not a line. */
  exact: boolean;
  /** Some typed word fit only with a typo. */
  fuzzy: boolean;
  /** Every typed word that fit, fit only with a typo: never a verdict, only „Czy chodzi o…”. */
  typoOnly?: true;
}

/**
 * The answer under the field. `prompt`: only words that tell nothing („garmin”, „mój zegarek”).
 * `help` („nie wiem”, „nie pamiętam”) opens „Gdzie znajdę nazwę modelu?”. `one`: a model, with
 * namesakes that answer the same (`same`) or differently (`other`); `title` keeps every number the
 * person typed. `line`: only line words were typed and its models answer differently. `guess`:
 * every match was a typo, or one typed word fits nothing — „Czy chodzi o…”. `unknown`: nothing fits;
 * with a model number, the nearest numbers of that line.
 */
export type Answer =
  | { kind: 'prompt' }
  | { kind: 'help' }
  | { kind: 'one'; hit: Hit; title: string; same: Hit[]; other: Hit[] }
  | { kind: 'line'; hits: Hit[] }
  | { kind: 'guess'; hits: Hit[] }
  | { kind: 'unknown'; near: Hit[] };
