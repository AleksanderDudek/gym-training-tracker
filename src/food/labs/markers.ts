/**
 * The markers the app understands: one entry per test, used by the reader (aliases, units), the
 * verdicts (ranges, targets) and the diet plan (`diet`, `retestWeeks`). Ranges are for adults;
 * sources are in `docs/research/badania-laboratoryjne.md`.
 *
 * Values are kept in one canonical unit per marker, the one Polish labs print most often
 * (mg/dl for glucose and lipids, ng/ml for vitamin D, pg/ml for B12…). A value printed in
 * another unit is converted on reading; the printed text stays in the result as well.
 */

export type MarkerGroup =
  | 'cbc'
  | 'iron'
  | 'vitamins'
  | 'minerals'
  | 'lipids'
  | 'glucose'
  | 'liver'
  | 'kidney'
  | 'thyroid'
  | 'inflammation'
  | 'urine';

export type Specimen = 'blood' | 'urine';

/** [low, high]; null is open on that side ("< 190", "> 40"). */
export type Range = readonly [number | null, number | null];

/** A conversion to the canonical unit: a factor, or a function where the scales are not proportional. */
export type Conversion = number | ((value: number) => number);

export interface Marker {
  id: string;
  group: MarkerGroup;
  specimen: Specimen;
  name: string;
  /** Short name for tables and charts, when the name is long. */
  short?: string;
  /** One sentence: what it shows. */
  about: string;
  /** Names as labs print them, folded (`fold`). Matched at the start of a row, longest first. */
  aliases: readonly string[];
  /** Canonical unit, as displayed. Empty for unitless values (pH, specific gravity, ratios). */
  unit: string;
  /** Folded unit (`foldUnit`) → conversion to the canonical unit. The canonical unit is listed too. */
  units: Readonly<Record<string, Conversion>>;
  digits: number;
  /** A urine strip result: negative / trace / positive rather than a number. */
  qualitative?: true;
  /** Adult reference range by sex, used when the printout has none. */
  ref?: Readonly<Record<Sex, Range>>;
  /** A guideline target that says more than "within the lab's range". */
  target?: { range: Range; source: string };
  /** How much food moves it. */
  diet: 'yes' | 'some' | 'no';
  /** Weeks until a change of diet can show in a retest. */
  retestWeeks?: number;
}

