/** The marker's own range for this sex, or null. */
export function refFor(marker: Marker, sex: Sex): Range | null {
  return marker.ref?.[sex] ?? null;
}

/** A value in a printed unit → canonical, or null when the unit is not one of the marker's. */
export function toCanonical(marker: Marker, value: number, unit: string): number | null {
  const conversion = marker.units[foldUnit(unit)];
  if (conversion === undefined) return null;
  return typeof conversion === 'number' ? value * conversion : conversion(value);
}

/** Every alias of every marker, longest first: "cholesterol hdl" must win over "cholesterol". */
export const ALIASES: readonly { alias: string; marker: Marker }[] = MARKERS_LIST.flatMap((marker) =>
  marker.aliases.map((alias) => ({ alias: fold(alias), marker })),
).sort((a, b) => b.alias.length - a.alias.length);
