// The pure part of the watch list generator (`npm run garmin:watches`, spec 2026-10-24 §4.11): the
// manifest, the Connect IQ SDK device files and the trimmed store catalog in, `src/watches/garmin.json`
// out. No file system and no network here — `watches.ts` reads and writes — so every rule runs on
// fixtures in `lib.test.ts`. Ported from the design prototype (`gen.ts`); names are folded with the
// app's own `fold`, so the generator and the check compare names the same way.
import type { Cap, SdkUnsupported, Supported } from '../../src/watches/types';
import { fold } from '../../src/watches/words';

/* ---------- inputs ---------- */

export interface SdkPart {
  number: string;
  firmwareVersion?: number | null;
  connectIQVersion: string;
  languages?: { code: string }[];
}

/** What the generator reads from `<id>/compiler.json`, plus the API list from `<id>.api.debug.xml`. */
export interface SdkDevice {
  id: string;
  displayName: string;
  webDocDeviceGroup: string;
  appTypes: { type: string; memoryLimit?: number }[];
  partNumbers: SdkPart[];
  /** The text of `<id>.api.debug.xml` ('' when the file is missing). */
  api: string;
}

/** One device type of the Connect IQ Store catalog, trimmed (`garmin/store-devices.json`). */
export interface StoreDevice {
  partNumber: string;
  name: string;
  additionalNames?: string[];
}

export interface Manifest {
  ids: string[];
  appId: string;
  minCiq: string;
}

/* ---------- output ---------- */

export interface SupportedOut extends Supported {
  /** The SDK's display name, as it is — for a person reading the file. */
  label: string;
  bg: 32 | 64;
}

export interface UnsupportedOut extends SdkUnsupported {
  label: string;
}

/** `src/watches/garmin.json`. */
export interface WatchList {
  $comment: string;
  sdk: string;
  appId: string;
  minCiq: string;
  supported: SupportedOut[];
  unsupported: UnsupportedOut[];
}

export const COMMENT =
  'Generated by npm run garmin:watches from garmin/manifest.xml and the Connect IQ SDK device files. Do not edit.';

/** What `--check` and the CI test say when the list and its sources differ. */
export const STALE = 'Lista zegarków nieaktualna — npm run garmin:watches';

/** The store catalog the app's compatibility list is built from (`--store`). */
export const STORE_CATALOG_URL = 'https://apps.garmin.com/api/appsLibraryExternalServices/api/asw/deviceTypes';

/* ---------- manifest, versions ---------- */

export function parseManifest(xml: string): Manifest {
  const ids = [...xml.matchAll(/<iq:product id="([^"]+)"/g)].map((m) => m[1]!);
  const appId = xml.match(/<iq:application id="([0-9a-f]{32})"/)?.[1];
  const minCiq = xml.match(/minApiLevel="([\d.]+)"/)?.[1];
  if (!appId || !minCiq || !ids.length) throw new Error('manifest.xml: brak identyfikatora aplikacji, minApiLevel albo listy produktów');
  return { ids, appId, minCiq };
}

/** The SDK version from `current-sdk.cfg` or an SDK path: „…/connectiq-sdk-mac-9.2.0-2026-06-09-…/” → 9.2.0. */
export const sdkVersion = (pathOrCfg: string): string | null =>
  pathOrCfg.match(/connectiq-sdk-[a-z]+-(\d+\.\d+\.\d+)/)?.[1] ?? null;

const parts = (s: string): number[] => s.split('.').map(Number);

/** Compares Connect IQ versions: „3.3.3” < „3.10.0”. */
export function cmpVersion(a: string, b: string): number {
  const x = parts(a);
  const y = parts(b);
  for (let i = 0; i < Math.max(x.length, y.length, 3); i++) if ((x[i] ?? 0) !== (y[i] ?? 0)) return (x[i] ?? 0) - (y[i] ?? 0);
  return 0;
}

/* ---------- names ---------- */

/** Brand words that start a full product name inside an SDK displayName segment. */
const BRAND =
  /^(Approach|D2|Descent|Enduro|epix|fēnix|Forerunner|Instinct|MARQ|Venu|vívoactive|vívo\w*|quatix|tactix|Edge|GPSMAP|eTrex|Montana|Oregon|Rino|Garmin|Captain Marvel|First Avenger|Darth Vader|Rey™|Mercedes)/u;
const SIZE = /^\d+mm$/;

const brandOf = (name: string): string => name.match(/^\S+/)![0]; // „fēnix®”, „Descent™”, „MARQ®”
const leadDigits = (s: string): string => s.match(/^\d+/)?.[0] ?? '';
const letters = (s: string): string => s.match(/^[A-Za-z]+/)?.[0] ?? '';
const sameModel = (a: string, b: string): boolean =>
  a === b || (!!leadDigits(a) && leadDigits(a) === leadDigits(b)) || (!!letters(a) && letters(a) === letters(b) && /\d/.test(a));

/**
 * „fēnix® 6 Pro / 6 Sapphire / … / quatix® 6” → every marketing name in full. A segment that starts
 * with a brand word is a full name. Otherwise: a size replaces the size („fēnix® 8 51mm”); the same
 * model token becomes brand + segment („fēnix® 6 Solar”, „Descent™ Mk2i”); after a „(Gen 2)” name,
 * brand + (Gen 2) + segment; a word after a sized name replaces the size („fēnix® 8 Pro MicroLED”);
 * anything else is base + segment („Instinct® 2 Solar”).
 */
export function expand(displayName: string): string[] {
  const segs = displayName.split(' / ').map((s) => s.trim());
  const out = [segs[0]!];
  let base = segs[0]!;
  for (const s of segs.slice(1)) {
    if (BRAND.test(s)) {
      out.push(s);
      base = s;
      continue;
    }
    const brand = brandOf(base);
    const rest = base.slice(brand.length).trim();
    if (SIZE.test(s)) out.push(/\d+mm$/.test(base) ? base.replace(/\d+mm$/, s) : `${base} ${s}`);
    else if (sameModel(s.split(' ')[0]!, rest.split(' ')[0] ?? '')) out.push(`${brand} ${s}`);
    else if (rest.startsWith('(Gen')) out.push(`${brand} ${rest.match(/^\(Gen \d+\)/)![0]} ${s}`);
    else if (/ \d+mm$/.test(base)) out.push(`${base.replace(/ \d+mm$/, '')} ${s}`);
    else out.push(`${base} ${s}`);
  }
  return [...new Set(out)];
}

const SERIES: [RegExp, string][] = [
  [/^Approach/, 'Approach'],
  [/^D2/, 'D2'],
  [/^Descent/, 'Descent'],
  [/^Enduro/, 'Enduro'],
  [/^epix/, 'epix'],
  [/^fēnix/, 'fēnix'],
  [/^Forerunner/, 'Forerunner'],
  [/^Instinct/, 'Instinct'],
  [/^MARQ/, 'MARQ'],
  [/^Venu/, 'Venu'],
  [/^vívoactive/, 'vívoactive'],
  [/^(Captain Marvel|First Avenger|Darth Vader|Rey)/, 'Legacy'],
  [/^Edge/, 'Edge'],
  [/^(GPSMAP|eTrex|Montana|Oregon|Rino)/, 'handheld'],
  [/^Garmin Swim/, 'Swim'],
];

/** The line a name belongs to, for the grouped list. */
export const seriesOf = (name: string): string => SERIES.find(([re]) => re.test(name))?.[1] ?? 'other';

/** Folds a name for comparing store names: lower case, no marks, no ®™, single spaces, „47 mm” = „47mm”. */
export const storeKey = (s: string): string =>
  fold(s)
    .replace(/[–—:()\-.,/]/g, ' ')
    .replace(/(\d)\s+mm\b/g, '$1mm')
    .replace(/\s+/g, ' ')
    .trim();

/** One-word fragments the catalog produces by splitting names at commas („Solar”, „AMOLED”). */
const FRAGMENTS = new Set(['solar', 'amoled', 'tactical', 'elite', 'microled', 'sapphire', 'camo', 'surf']);
const fragment = (s: string): boolean => FRAGMENTS.has(storeKey(s));

/** A store name tidied up: one kind of dash, single spaces, no padding („…ONE PIECE LUFFY ”). */
export const cleanName = (s: string): string => s.replace(/\s*–\s*/g, ' – ').replace(/\s+/g, ' ').trim();

/** Sorts names by their folded form — the same order on every machine. */
export function byFolded(a: string, b: string): number {
  const x = storeKey(a);
  const y = storeKey(b);
  if (x !== y) return x < y ? -1 : 1;
  return a < b ? -1 : a > b ? 1 : 0;
}

/* ---------- what a device can do ---------- */

const CAP_API: Record<Cap, string> = {
  stress: 'getStressHistory',
  bodyBattery: 'getBodyBatteryHistory',
  rides: 'getUserActivityHistory',
};
const CAPS = Object.keys(CAP_API) as Cap[];

/** All three history APIs arrived in Connect IQ 3.3: an older firmware lacks them even where the device lists them. */
export const CAP_MIN = '3.3.0';

/** The device's Polish (global) parts: the European version, the one sold in Poland. */
const hasPol = (p: SdkPart): boolean => !!p.languages?.some((l) => l.code === 'pol');

/** What a watch app can read on this part: the API must be listed and the part's Connect IQ at least 3.3. */
export const capsOf = (d: SdkDevice, part: SdkPart): Cap[] =>
  CAPS.filter((c) => d.api.includes(CAP_API[c]) && cmpVersion(part.connectIQVersion, CAP_MIN) >= 0);

/** Background memory: 32 — under 64 kB, 64 — 64 kB or more. */
export function bgOf(d: SdkDevice): 32 | 64 {
  const limit = d.appTypes.find((t) => t.type === 'background')?.memoryLimit;
  if (!limit) throw new Error(`${d.id}: brak pracy w tle (appTypes background) — aplikacja na nim nie działa`);
  return limit < 64 * 1024 ? 32 : 64;
}

/** Why the watch app cannot run on a device outside the manifest. */
export function unsupportedReason(d: SdkDevice, minCiq: string): Pick<SdkUnsupported, 'reason' | 'kind' | 'ciq'> {
  const types = new Set(d.appTypes.map((t) => t.type));
  const maxCiq = d.partNumbers.map((p) => p.connectIQVersion).sort(cmpVersion).at(-1) ?? '0.0.0';
  if (d.webDocDeviceGroup !== 'Watches/Wearables') return { reason: 'notWatch', kind: d.webDocDeviceGroup === 'Edge' ? 'bike' : 'handheld' };
  if (!types.has('watchApp')) return { reason: 'noApps', ciq: maxCiq };
  if (!types.has('background')) return { reason: 'noBackground', ciq: maxCiq };
  if (cmpVersion(maxCiq, minCiq) < 0) return { reason: 'oldCiq', ciq: maxCiq };
  return { reason: 'notListed', ciq: maxCiq };
}

/* ---------- the store catalog ---------- */

/** The catalog's answer, checked and trimmed to what the list uses: part number, name, other names. */
export function trimStore(raw: unknown): StoreDevice[] {
  if (!Array.isArray(raw) || !raw.length) throw new Error('katalog sklepu: oczekiwana niepusta lista urządzeń');
  const out = raw.map((d: unknown, i): StoreDevice => {
    const r = (typeof d === 'object' && d !== null ? d : {}) as Record<string, unknown>;
    if (typeof r.partNumber !== 'string' || typeof r.name !== 'string')
      throw new Error(`katalog sklepu: urządzenie ${i} bez partNumber albo name`);
    const more = Array.isArray(r.additionalNames) ? r.additionalNames.filter((n): n is string => typeof n === 'string') : [];
    return { partNumber: r.partNumber, name: r.name, ...(more.length ? { additionalNames: more } : {}) };
  });
  return out.sort((a, b) => (a.partNumber !== b.partNumber ? (a.partNumber < b.partNumber ? -1 : 1) : byFolded(a.name, b.name)));
}

/**
 * Store devices the SDK device files don't know, neither by part number nor by name: a watch newer
 * than the SDK Manager download (MARQ Gen 3 was one) needs a `notYet` entry in `src/watches/extra.ts`.
 */
export function storeOnly(store: StoreDevice[], devices: SdkDevice[]): StoreDevice[] {
  const sdkParts = new Set(devices.flatMap((d) => d.partNumbers.map((p) => p.number)));
  const sdkNames = new Set(devices.flatMap((d) => expand(d.displayName)).map(storeKey));
  return store.filter(
    (s) => !sdkParts.has(s.partNumber) && ![s.name, ...(s.additionalNames ?? [])].some((n) => sdkNames.has(storeKey(cleanName(n)))),
  );
}

/* ---------- the list ---------- */

export interface BuildInput {
  manifest: Manifest;
  devices: SdkDevice[];
  store: StoreDevice[];
  sdk: string;
}

/** The whole list, deterministic: supported in manifest order, unsupported by name, aliases sorted. */
export function buildList({ manifest, devices, store, sdk }: BuildInput): { list: WatchList; warnings: string[] } {
  const warnings: string[] = [];
  const byId = new Map(devices.map((d) => [d.id, d]));
  const storeByPart = new Map<string, StoreDevice[]>();
  for (const s of store) storeByPart.set(s.partNumber, [...(storeByPart.get(s.partNumber) ?? []), s]);
  const storeNames = (p: SdkPart): string[] =>
    (storeByPart.get(p.number) ?? []).flatMap((s) => [s.name, ...(s.additionalNames ?? [])]).map(cleanName).flatMap(expand);

  const missing = manifest.ids.filter((id) => !byId.has(id));
  if (missing.length) throw new Error(`produkty z manifest.xml, których nie ma w katalogu urządzeń SDK: ${missing.join(', ')}`);

  const supported = manifest.ids.map((id): SupportedOut => {
    const d = byId.get(id)!;
    const names = expand(d.displayName);
    const pol = d.partNumbers.filter(hasPol);
    const other = d.partNumbers.filter((p) => !hasPol(p));
    if (!pol.length) throw new Error(`${id}: żaden numer części nie ma polskiego — nie wiem, która wersja jest europejska`);
    // What the Polish (global) firmware shares: the newest global part decides.
    const newestPol = pol.reduce((a, b) => (cmpVersion(a.connectIQVersion, b.connectIQVersion) >= 0 ? a : b));
    const have = capsOf(d, newestPol);
    const lacks = CAPS.filter((c) => !have.includes(c));
    // Needs the newest watch software: an older firmware of the same model (a known version number,
    // lower than the newest global one) is below Connect IQ 3.3, so it lacks what the newest has.
    const older = d.partNumbers.filter(
      (p) =>
        typeof p.firmwareVersion === 'number' &&
        typeof newestPol.firmwareVersion === 'number' &&
        p.firmwareVersion < newestPol.firmwareVersion &&
        cmpVersion(p.connectIQVersion, CAP_MIN) < 0,
    );
    const newest = older.length ? have.filter((c) => older.some((p) => !capsOf(d, p).includes(c))) : [];
    // Asian (APAC) parts: no Polish. What they lack beyond the global version.
    const apacLacks = CAPS.filter((c) => have.includes(c) && other.some((p) => !capsOf(d, p).includes(c)));
    // A store name listed only under Asian parts belongs to the Asian version („Instinct® 2 Dual Power”).
    const globalKeys = new Set(pol.flatMap(storeNames).map(storeKey));
    const apacKeys = new Set(other.flatMap(storeNames).map(storeKey));
    const apacOnly = (n: string): boolean => apacLacks.length > 0 && apacKeys.has(storeKey(n)) && !globalKeys.has(storeKey(n));
    const apacNames = names.filter(apacOnly);
    const seen = new Set(names.map(storeKey));
    const aliases: string[] = [];
    for (const n of d.partNumbers.flatMap(storeNames)) {
      if (fragment(n) || seen.has(storeKey(n))) continue;
      seen.add(storeKey(n));
      if (apacOnly(n)) apacNames.push(n);
      else aliases.push(n);
    }
    return {
      id,
      series: seriesOf(names[0]!),
      label: d.displayName,
      names: names.filter((n) => !apacOnly(n)),
      ...(aliases.length ? { aliases } : {}),
      ciq: newestPol.connectIQVersion,
      bg: bgOf(d),
      parts: d.partNumbers.map((p) => p.number),
      ...(lacks.length ? { lacks } : {}),
      ...(newest.length ? { newest } : {}),
      ...(apacLacks.length ? { apac: { lacks: apacLacks, ...(apacNames.length ? { names: apacNames } : {}) } } : {}),
    };
  });

  // A store alias under two products („Instinct® 3 – 50 mm” is AMOLED and Solar) tells nothing: drop it.
  const aliasCount = new Map<string, number>();
  for (const s of supported) for (const a of s.aliases ?? []) aliasCount.set(storeKey(a), (aliasCount.get(storeKey(a)) ?? 0) + 1);
  const shared = new Set<string>();
  for (const s of supported) {
    if (!s.aliases) continue;
    for (const a of s.aliases) if (aliasCount.get(storeKey(a))! > 1) shared.add(a);
    const kept = s.aliases.filter((a) => aliasCount.get(storeKey(a)) === 1).sort(byFolded);
    if (kept.length) s.aliases = kept;
    else delete s.aliases;
  }
  if (shared.size) warnings.push(`pominięte nazwy ze sklepu, które ma kilka produktów: ${[...shared].sort(byFolded).join(', ')}`);

  const inManifest = new Set(manifest.ids);
  const supportedNames = new Set(supported.flatMap((s) => [...s.names, ...(s.aliases ?? [])]).map(storeKey));
  const spelled = new Set<string>();
  const unsupported = devices
    .filter((d) => !inManifest.has(d.id))
    .sort((a, b) => byFolded(a.displayName, b.displayName))
    .map((d): UnsupportedOut => {
      const why = unsupportedReason(d, manifest.minCiq);
      if (why.reason === 'notListed')
        warnings.push(`${d.id} (${d.displayName}) spełnia warunki listy — zegarek z aplikacjami, pracą w tle i Connect IQ ≥ ${manifest.minCiq} — a nie ma go w manifest.xml`);
      const names = expand(d.displayName);
      const seen = new Set(names.map(storeKey));
      const aliases: string[] = [];
      for (const n of d.partNumbers.flatMap((p) => (storeByPart.get(p.number) ?? []).flatMap((s) => [s.name, ...(s.additionalNames ?? [])])).map(cleanName)) {
        if (fragment(n) || seen.has(storeKey(n))) continue;
        seen.add(storeKey(n));
        // „vívoactive® 3 Music” is also the store's name of the LTE model: the supported one keeps it.
        if (supportedNames.has(storeKey(n))) spelled.add(n);
        else aliases.push(n);
      }
      return {
        id: d.id,
        series: seriesOf(names[0]!),
        label: d.displayName,
        names,
        ...(aliases.length ? { aliases: aliases.sort(byFolded) } : {}),
        reason: why.reason,
        ...(why.kind ? { kind: why.kind } : {}),
        ...(why.ciq ? { ciq: why.ciq } : {}),
      };
    });
  if (spelled.size)
    warnings.push(`pominięte nazwy ze sklepu przy nieobsługiwanych, bo to nazwy obsługiwanych: ${[...spelled].sort(byFolded).join(', ')}`);

  return { list: { $comment: COMMENT, sdk, appId: manifest.appId, minCiq: manifest.minCiq, supported, unsupported }, warnings };
}

/** The file as written: 2-space indent and a trailing newline. */
export const serialize = (value: unknown): string => `${JSON.stringify(value, null, 2)}\n`;

/** Which ids differ between two lists — for `--check` to say what changed. */
export function changedIds(before: Pick<WatchList, 'supported' | 'unsupported'>, after: Pick<WatchList, 'supported' | 'unsupported'>): string[] {
  const map = (l: Pick<WatchList, 'supported' | 'unsupported'>) =>
    new Map<string, string>([...l.supported, ...l.unsupported].map((x) => [x.id, JSON.stringify(x)]));
  const a = map(before);
  const b = map(after);
  return [...new Set([...a.keys(), ...b.keys()])].filter((id) => a.get(id) !== b.get(id)).sort();
}
