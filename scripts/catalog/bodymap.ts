/**
 * Generates the body-map outlines (`src/data/bodymap/{male,female}.ts`) from MuscleMap by
 * Melih Colpan (MIT, github.com/melihcolpan/MuscleMap), pinned to one commit. MuscleMap ships its
 * SVG path data as Swift source; we read the strings and group them into the app's 16 muscle
 * groups. Sub-groups are dropped except the front and rear deltoid, which the app counts on their
 * own (shoulders are three groups here). Non-muscle parts become the silhouette.
 *
 *   npm run catalog:bodymap
 */
import { mkdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = 'melihcolpan/MuscleMap';
const COMMIT = 'd53ddf4d480b65979f1008b203e6b6eda0e67e54';

/** MuscleMap slug → app muscle group (`null` = silhouette). Unlisted slugs are dropped. */
const SLUG: Record<string, string | null> = {
  chest: 'klatka',
  serratus: 'klatka',
  abs: 'brzuch',
  obliques: 'brzuch',
  biceps: 'biceps',
  triceps: 'triceps',
  forearm: 'przedramiona',
  deltoids: 'bark-bok',
  frontDeltoid: 'bark-przod',
  rearDeltoid: 'bark-tyl',
  rotatorCuff: 'bark-tyl',
  trapezius: 'plecy-gora',
  rhomboids: 'plecy-gora',
  upperBack: 'najszersze',
  lowerBack: 'prostowniki',
  gluteal: 'posladki',
  hamstring: 'dwuglowe',
  quadriceps: 'czworoglowe',
  adductors: 'przywodziciele',
  calves: 'lydki',
  tibialis: 'lydki',
  head: null,
  hair: null,
  neck: null,
  hands: null,
  feet: null,
  knees: null,
  ankles: null,
};
/** Drawn last, over their parent (`deltoids`). */
const OVERLAY = new Set(['frontDeltoid', 'rearDeltoid']);

/** View boxes from MuscleMap's `BodyViewBox`. */
const VIEW = {
  male: { front: [0, 95, 727, 1280], back: [718, 95, 727, 1280] },
  female: { front: [0, 0, 650, 1450], back: [823, 0, 650, 1450] },
} as const;

async function parts(file: string): Promise<[string | null, string][]> {
  const url = `https://raw.githubusercontent.com/${REPO}/${COMMIT}/Sources/MuscleMap/Data/${file}`;
  const res = await fetch(url);
  if (!res.ok) throw new Error(`HTTP ${res.status} for ${url}`);
  const src = await res.text();
  const blocks = src.split('BodyPartPathData(').slice(1);
  const base: [string | null, string][] = [];
  const over: [string | null, string][] = [];
  for (const b of blocks) {
    const slug = b.match(/slug:\s*\.(\w+)/)?.[1];
    if (!slug || !(slug in SLUG)) continue;
    const d = [...b.matchAll(/"([^"]+)"/g)].map((m) => m[1]).join(' ');
    if (d) (OVERLAY.has(slug) ? over : base).push([SLUG[slug]!, d]);
  }
  // Silhouette first, so the muscles sit on top of it.
  return [...base.filter(([m]) => m === null), ...base.filter(([m]) => m !== null), ...over];
}

async function main(): Promise<void> {
  const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
  const out = join(root, 'src', 'data', 'bodymap');
  mkdirSync(out, { recursive: true });
  for (const sex of ['male', 'female'] as const) {
    const cap = sex === 'male' ? 'Male' : 'Female';
    const front = await parts(`${cap}FrontPaths.swift`);
    const back = await parts(`${cap}BackPaths.swift`);
    const body = `// Generated by scripts/catalog/bodymap.ts — do not edit.
// Outlines from MuscleMap by Melih Colpan (github.com/melihcolpan/MuscleMap, commit ${COMMIT.slice(0, 8)}),
// MIT License, Copyright (c) 2026 Melih Colpan. Full licence text: public/licenses/MuscleMap.txt.
import type { BodyViews } from './types';

const views: BodyViews = ${JSON.stringify(
      { front: { box: VIEW[sex].front, parts: front }, back: { box: VIEW[sex].back, parts: back } },
      null,
      0,
    )};
export default views;
`;
    writeFileSync(join(out, `${sex}.ts`), body);
    console.log(`${sex}: front ${front.length} parts, back ${back.length} parts`);
  }
}

void main();
